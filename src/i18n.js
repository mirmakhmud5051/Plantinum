export const getLanguage = () => language;
export const setLanguage = (value) => (language = value === "en" ? "en" : "uz");
export const normalizeSearch = (value) => value.normalize("NFKD").toLowerCase().replace(/['‘’ʻʼ`]/g, "").trim();

export function t(value) {
  if (language === "en" || typeof value !== "string") return value;
  const body = value.trim(), key = body.replace(/\s+/g, " ");
  let result = Object.hasOwn(UZ, key) ? UZ[key] : undefined;
  if (result === undefined) {
    const rules = [
      [/^(\d+) plants to discover$/, (_, n) => `${n} ta o‘simlik`],
      [/^(\d+) objects to discover$/, (_, n) => `${n} ta bezak`],
      [/^(\d+) plants, endless possibilities$/, (_, n) => `${n} ta o‘simlik, cheksiz imkoniyat`],
      [/^(\d+)% grown$/, (_, n) => `${n}% o‘sgan`],
      [/^(Seed|Sprout|Young|Growing|Mature)\s*·\s*(\d+)% grown$/, (_, stage, n) => `${t(stage)} · ${n}% o‘sgan`],
      [/^Hydration (\d+)%$/, (_, n) => `Namlik ${n}%`],
      [/^(\d+)× (Normal|Maximum|Faster)$/, (_, n, speed) => `${n}× ${t(speed)}`],
      [/^(\d+) × (\d+) m of possibility$/, (_, w, h) => `${w} × ${h} m ochiq olam`],
      [/^Choose (.+)$/, (_, name) => `${t(name)} tanlash`],
      [/^Voxel (.+)$/, (_, name) => `${t(name)} voxel modeli`],
      [/^(.+) selected\. Choose a gardening tool to care for it\.$/, (_, name) => `${t(name)} tanlandi. Parvarish qilish uchun asbob tanlang.`],
      [/^(.+) planted\. A little water will help it grow\.$/, (_, name) => `${t(name)} ekildi. Sug‘orsangiz, tezroq o‘sadi.`],
      [/^Ready to plant another (.+)\.$/, (_, name) => `${t(name)} nusxasini joylashtirish uchun yerga bosing.`],
      [/^(\d+) plants watered\. Happy roots, happy garden\.$/, (_, n) => `${n} ta o‘simlik sug‘orildi. Bog‘ingiz yashnaydi!`],
      [/^(.+) topiary\. A little living sculpture\.$/, (_, shape) => `${t(shape)} shakli berildi. Tirik san’at asari!`],
      [/^Welcome to (.+)\. Plant a little possibility\.$/, (_, zone) => {
        const name = Object.keys(UZ).find((k) => k.toLowerCase() === zone);
        return `${t(name || zone)}: xush kelibsiz! Yangi nihollar eking.`;
      }],
      [/^A little (?:slower|faster)\. Growing at (\d+)× speed\.$/, (_, n) => `O‘sish va vaqt tezligi: ${n}×.`],
      [/^(.+) · (C|R|Ctrl\+Z|[1-8])$/, (_, label, shortcut) => `${t(label)} · ${shortcut}`],
    ];
    for (const [pattern, format] of rules) {
      if (pattern.test(key)) { result = key.replace(pattern, format); break; }
    }
  }
  return result === undefined ? value : value.replace(body, result);
}

// Translate only display text and accessible labels, never IDs, values or data attributes.
export function localizeHTML(markup) {
  if (language === "en") return markup;
  const template = document.createElement("template");
  template.innerHTML = markup;
  const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) walker.currentNode.nodeValue = t(walker.currentNode.nodeValue);
  for (const el of template.content.querySelectorAll("[title],[aria-label],[placeholder],[alt]")) {
    for (const attr of ["title", "aria-label", "placeholder", "alt"])
      if (el.hasAttribute(attr)) el.setAttribute(attr, t(el.getAttribute(attr)));
  }
  return template.innerHTML;
}
